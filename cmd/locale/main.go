// Command locale checks pkg/i18n/locales/*.yml and generates pkg/i18n/keys_gen.go,
// one Key constant per key in en.yml (RECORD_NOT_FOUND -> i18n.RecordNotFound).
//
// Run from anywhere inside the module: `make locale` or `go run ./cmd/locale`.
// It fails if a locale is missing a key, has an extra key, or uses different {placeholders}.
package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"

	"github.com/goccy/go-yaml"
)

const (
	localesDir = "pkg/i18n/locales"
	outFile    = "pkg/i18n/keys_gen.go"
	sourceLang = "en"
)

// Must match i18n.Langs.
var langs = []string{"en", "km", "ms"}

var (
	keyPattern         = regexp.MustCompile(`^[A-Z][A-Z0-9]*(_[A-Z0-9]+)*$`)
	placeholderPattern = regexp.MustCompile(`\{([a-zA-Z0-9_]+)\}`)
	// Parts written in upper case in Go names (Go style: ID, not Id).
	initialisms = map[string]bool{"ID": true, "IDS": true, "URL": true, "API": true, "HTTP": true, "JSON": true, "OTP": true, "UUID": true}
)

type entry struct {
	key, msg string
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "locale:", err)
		os.Exit(1)
	}
}

func run() error {
	root, err := moduleRoot()
	if err != nil {
		return err
	}

	locales := make(map[string][]entry, len(langs))
	for _, lang := range langs {
		entries, err := readLocale(filepath.Join(root, localesDir, lang+".yml"))
		if err != nil {
			return err
		}
		locales[lang] = entries
	}

	if problems := validate(locales); len(problems) > 0 {
		return fmt.Errorf("%d problem(s):\n  %s", len(problems), strings.Join(problems, "\n  "))
	}

	src, err := generate(locales[sourceLang])
	if err != nil {
		return err
	}
	out := filepath.Join(root, outFile)
	if err := os.WriteFile(out, src, 0o644); err != nil {
		return err
	}
	fmt.Printf("locale: wrote %d keys to %s\n", len(locales[sourceLang]), outFile)
	return nil
}

// readLocale keeps the file's key order, so constants follow en.yml's grouping.
func readLocale(file string) ([]entry, error) {
	data, err := os.ReadFile(file)
	if err != nil {
		return nil, err
	}
	var items yaml.MapSlice
	if err := yaml.Unmarshal(data, &items); err != nil {
		return nil, fmt.Errorf("%s: %w", filepath.Base(file), err)
	}
	entries := make([]entry, 0, len(items))
	for _, item := range items {
		key, ok := item.Key.(string)
		msg, okMsg := item.Value.(string)
		if !ok || !okMsg {
			return nil, fmt.Errorf("%s: %v must be a string key with a string message", filepath.Base(file), item.Key)
		}
		entries = append(entries, entry{key, msg})
	}
	return entries, nil
}

func validate(locales map[string][]entry) []string {
	var problems []string
	source := toMap(locales[sourceLang])

	for _, e := range locales[sourceLang] {
		if !keyPattern.MatchString(e.key) {
			problems = append(problems, fmt.Sprintf("%s.yml: key %q must be UPPER_SNAKE_CASE", sourceLang, e.key))
		}
		if strings.TrimSpace(e.msg) == "" {
			problems = append(problems, fmt.Sprintf("%s.yml: %s has an empty message", sourceLang, e.key))
		}
	}

	for _, lang := range langs {
		if lang == sourceLang {
			continue
		}
		msgs := toMap(locales[lang])
		for _, e := range locales[sourceLang] {
			msg, ok := msgs[e.key]
			switch {
			case !ok:
				problems = append(problems, fmt.Sprintf("%s.yml: missing %s", lang, e.key))
			case strings.TrimSpace(msg) == "":
				problems = append(problems, fmt.Sprintf("%s.yml: %s has an empty message", lang, e.key))
			case !slices.Equal(placeholders(msg), placeholders(e.msg)):
				problems = append(problems, fmt.Sprintf("%s.yml: %s uses placeholders %v, %s.yml uses %v",
					lang, e.key, placeholders(msg), sourceLang, placeholders(e.msg)))
			}
		}
		for _, e := range locales[lang] {
			if _, ok := source[e.key]; !ok {
				problems = append(problems, fmt.Sprintf("%s.yml: %s is not in %s.yml", lang, e.key, sourceLang))
			}
		}
	}
	return problems
}

func generate(entries []entry) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/locale from pkg/i18n/locales/*.yml; DO NOT EDIT.\n\n")
	b.WriteString("package i18n\n\n")

	names := make(map[string]string, len(entries))
	b.WriteString("const (\n")
	for _, e := range entries {
		name := goName(e.key)
		if other, dup := names[name]; dup {
			return nil, fmt.Errorf("keys %s and %s both become %s", other, e.key, name)
		}
		names[name] = e.key
		fmt.Fprintf(&b, "\t// %s\n\t%s Key = %q\n", oneLine(e.msg), name, e.key)
	}
	b.WriteString(")\n\n")

	b.WriteString("// AllKeys lists every key in en.yml.\nvar AllKeys = []Key{\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "\t%s,\n", goName(e.key))
	}
	b.WriteString("}\n")

	return format.Source(b.Bytes())
}

// goName turns RECORD_NOT_FOUND into RecordNotFound and INVALID_ID into InvalidID.
func goName(key string) string {
	var b strings.Builder
	for _, part := range strings.Split(key, "_") {
		if initialisms[part] {
			b.WriteString(part)
			continue
		}
		b.WriteString(part[:1] + strings.ToLower(part[1:]))
	}
	return b.String()
}

func placeholders(msg string) []string {
	var names []string
	for _, m := range placeholderPattern.FindAllStringSubmatch(msg, -1) {
		names = append(names, m[1])
	}
	slices.Sort(names)
	return slices.Compact(names)
}

func toMap(entries []entry) map[string]string {
	m := make(map[string]string, len(entries))
	for _, e := range entries {
		m[e.key] = e.msg
	}
	return m
}

func oneLine(s string) string {
	return strings.Join(strings.Fields(s), " ")
}

func moduleRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", errors.New("go.mod not found; run inside the module")
		}
		dir = parent
	}
}
