package routes

import (
	"net/http"

	"github.com/Fazann/notedbook-backend/config"
	_ "github.com/Fazann/notedbook-backend/docs" // generated by `make swagger`
	"github.com/Fazann/notedbook-backend/shared/middleware"
	"github.com/gin-gonic/gin"
	swaggerFiles "github.com/swaggo/files"
	ginSwagger "github.com/swaggo/gin-swagger"
)

func InitRouter(r *gin.Engine) {
	r.Use(middleware.CORS())

	// Swagger UI at /swagger/index.html; not served in production.
	if config.Environment != "production" {
		r.GET("/docs/*any", ginSwagger.WrapHandler(swaggerFiles.Handler))
	}

	r.GET("ping", func(c *gin.Context) {
		c.JSON(http.StatusOK, "Ok")
	})

	initAPIRoute(r)
}
