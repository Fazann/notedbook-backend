//go:build !noswagger

package routes

import (
	"github.com/Fazann/notedbook-backend/config"
	_ "github.com/Fazann/notedbook-backend/docs" // generated by `make swagger`
	"github.com/Fazann/notedbook-backend/pkg/logger"
	"github.com/gin-gonic/gin"
	swaggerFiles "github.com/swaggo/files"
	ginSwagger "github.com/swaggo/gin-swagger"
)

// initSwaggerRoute serves the Swagger UI at /docs/index.html; not served in production.
// Build with -tags noswagger to leave it (and its ~9 MB of assets) out of the binary.
func initSwaggerRoute(r *gin.Engine) {
	if config.Environment != "production" {
		r.GET("/docs/*any", ginSwagger.WrapHandler(swaggerFiles.Handler, ginSwagger.PersistAuthorization(true)))
		logger.Info("swagger UI enabled", "path", "/docs/index.html")
	}
}
